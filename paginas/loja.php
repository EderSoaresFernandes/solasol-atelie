<script>
const fotosGaleria = [
    { src: 'imagens/atelieFachada.jpeg', legenda: 'Nossa Fachada' },
    { src: 'imagens/placaFachadaAtelie.jpg', legenda: 'Identificação Exclusiva' },
    { src: 'imagens/internaAtelieMontado.jpg', legenda: 'Showroom Interno' },
    { src: 'imagens/internaAtelie.jpg', legenda: 'Ambiente Aconchegante' }
];

let indiceAtual = 0;

function abrirLightbox(src, legenda) {
    indiceAtual = fotosGaleria.findIndex(item => item.src === src);
    if (indiceAtual === -1) indiceAtual = 0;
    atualizarLightbox();
    let modal = new bootstrap.Modal(document.getElementById('lightboxModal'));
    modal.show();
}

function mudarFotoLightbox(direcao) {
    indiceAtual += direcao;
    if (indiceAtual < 0) indiceAtual = fotosGaleria.length - 1;
    if (indiceAtual >= fotosGaleria.length) indiceAtual = 0;
    atualizarLightbox();
}

function atualizarLightbox() {
    document.getElementById('imgLightbox').src = fotosGaleria[indiceAtual].src;
    document.getElementById('legendaLightbox').innerText = fotosGaleria[indiceAtual].legenda;
}
</script>